#!/usr/bin/env node

/**
 * Keeps the Russian locale under `docs-site/ru/` in step with the English pages.
 *
 * A Russian page is a hand-written translation and is committed. This script never touches one: it
 * only creates a placeholder for an English page that has no Russian counterpart yet, and deletes a
 * Russian page whose English original is gone. A placeholder carries the English body under a
 * banner, so the site still builds and the language switcher still lands on the page the reader was
 * on — but `--check` fails while any placeholder is left, which is what keeps them from shipping
 * quietly.
 *
 * `--check` additionally guards the two things a translation breaks silently:
 *
 *  - every heading must keep the English anchor with an explicit `{#…}`, or every cross-page link
 *    into that page dies the moment the heading is translated;
 *  - every absolute in-site link must stay inside `/ru/`, or a click drops the reader back into
 *    English mid-guide.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = path.join(ROOT, 'docs-site');
const RU_DIR = path.join(SRC_DIR, 'ru');

const SKIP_DIRS = new Set(['node_modules', '.vitepress', 'public', 'ru']);
const SKIP_FILES = new Set(['README.md']);

const BANNER = '<!-- Untranslated placeholder — run `npm run ru:sync` after translating. -->';
const LEGACY_BANNER = '<!-- Generated by scripts/generate-ru-mirrors.mjs — edit the English page instead. -->';

// Prose has to be mostly Cyrillic for the page to count as translated. The threshold is low on
// purpose: API pages are half identifiers, and a page that trips this is half-done, not stylistically off.
const MIN_CYRILLIC_SHARE = 0.45;

const check = process.argv.includes('--check');
const fixAnchors = process.argv.includes('--anchors');

function collectPages(dir, prefix = '') {
  const pages = [];

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      pages.push(...collectPages(path.join(dir, entry.name), `${prefix}${entry.name}/`));
      continue;
    }

    if (!entry.name.endsWith('.md') || SKIP_FILES.has(entry.name)) continue;
    if (prefix === '' && entry.name === 'index.md') continue;

    pages.push(`${prefix}${entry.name}`);
  }

  return pages;
}

// Absolute in-site links have to gain the `/ru` prefix or a click leaves the locale; relative ones
// already resolve inside the mirror, and anything with a scheme is somebody else's site.
function localizeLinks(markdown) {
  return markdown.replace(/\]\(\/(?!\/)/g, '](/ru/');
}

function splitFrontmatter(markdown) {
  const match = /^---\r?\n[\s\S]*?\r?\n---\r?\n/.exec(markdown);
  return match ? [match[0], markdown.slice(match[0].length)] : ['', markdown];
}

function isPlaceholder(markdown) {
  return markdown.includes(BANNER) || markdown.includes(LEGACY_BANNER);
}

// `@mdit-vue/shared`'s slugify, reproduced so the check runs without the docs-site install (the site
// is only ever built in CI). Keep in step with that package if VitePress changes anchor generation.
function slugify(text) {
  return text
    .normalize('NFKD')
    .replace(/[\u0300-\u036F]/g, '')
    .replace(/[\u0000-\u001F]/g, '')
    .replace(/[\s~`!@#$%^&*()\-_+=[\]{}|\\;:"'“”‘’<>,.?/]+/g, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/^(\d)/, '_$1')
    .toLowerCase();
}

function eachHeading(markdown, visit) {
  const lines = markdown.split('\n');
  let inFence = false;

  lines.forEach((line, index) => {
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence;
      return;
    }

    if (inFence) return;

    const match = /^(#{2,6})\s+(.+?)\s*$/.exec(line);
    if (!match) return;

    const explicit = /\{#([^}]+)\}\s*$/.exec(match[2]);
    const text = match[2]
      .replace(/\{#[^}]+\}\s*$/, '')
      .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
      .replace(/<[^>]+>/g, '');

    visit({ index, hashes: match[1], text: text.trim(), anchor: explicit ? explicit[1] : slugify(text), explicit: Boolean(explicit) }, lines);
  });

  return lines;
}

// Two headings with the same text are two different anchors: markdown-it-anchor keeps the first and
// suffixes the rest, so `## Building entries` twice is `#building-entries` and `#building-entries-1`.
// A heading that spells its own `{#id}` is taken at its word and never suffixed.
function headings(markdown) {
  const found = [];
  const taken = new Set();

  eachHeading(markdown, (heading) => {
    let anchor = heading.anchor;

    if (!heading.explicit) {
      for (let suffix = 1; taken.has(anchor); suffix += 1) anchor = `${heading.anchor}-${suffix}`;
    }

    taken.add(anchor);
    found.push({ ...heading, anchor });
  });

  return found;
}

// Translating a heading changes the anchor VitePress derives from it, and every link into that page
// dies with it. The English anchor is the contract, so it is written back positionally rather than
// left to whoever translated the page.
function realignAnchors(page) {
  const target = path.join(RU_DIR, page);
  const english = headings(fs.readFileSync(path.join(SRC_DIR, page), 'utf-8'));
  const russian = fs.readFileSync(target, 'utf-8');
  const found = headings(russian);

  if (found.length !== english.length) {
    return `${path.join('ru', page)} — ${found.length} headings against ${english.length} in English; align the structure by hand`;
  }

  let cursor = 0;
  const lines = eachHeading(russian, (heading, all) => {
    all[heading.index] = `${heading.hashes} ${heading.text} {#${english[cursor].anchor}}`;
    cursor += 1;
  });

  const rewritten = lines.join('\n');
  if (rewritten !== russian) fs.writeFileSync(target, rewritten);
  return null;
}

function cyrillicShare(markdown) {
  const [, body] = splitFrontmatter(markdown);
  let inFence = false;
  let cyrillic = 0;
  let latin = 0;

  for (const line of body.split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence;
      continue;
    }

    if (inFence) continue;

    cyrillic += (line.match(/[а-яёА-ЯЁ]/g) || []).length;
    latin += (line.match(/[a-zA-Z]/g) || []).length;
  }

  return cyrillic + latin === 0 ? 1 : cyrillic / (cyrillic + latin);
}

function placeholderFor(page) {
  const source = fs.readFileSync(path.join(SRC_DIR, page), 'utf-8');
  const [frontmatter, body] = splitFrontmatter(source);

  return `${frontmatter}\n${BANNER}\n${localizeLinks(body)}`;
}

function removeStalePages(pages) {
  const keep = new Set(pages.map((page) => path.join(RU_DIR, page)));
  const stale = [];

  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);

      if (entry.isDirectory()) {
        walk(full);
        if (!check && fs.readdirSync(full).length === 0) fs.rmdirSync(full);
        continue;
      }

      if (full === path.join(RU_DIR, 'index.md') || keep.has(full)) continue;
      stale.push(path.relative(SRC_DIR, full));
      if (!check) fs.unlinkSync(full);
    }
  };

  if (fs.existsSync(RU_DIR)) walk(RU_DIR);
  return stale;
}

const pages = collectPages(SRC_DIR);
const problems = [];
let created = 0;

if (fixAnchors) {
  const failures = pages
    .filter((page) => fs.existsSync(path.join(RU_DIR, page)))
    .filter((page) => !isPlaceholder(fs.readFileSync(path.join(RU_DIR, page), 'utf-8')))
    .map(realignAnchors)
    .filter(Boolean);

  for (const failure of failures) console.error(`  ${failure}`);
  console.log(`docs-site/ru — anchors realigned${failures.length ? `, ${failures.length} page(s) need manual work` : ''}`);
  process.exit(failures.length > 0 ? 1 : 0);
}

for (const page of pages) {
  const target = path.join(RU_DIR, page);

  if (!fs.existsSync(target)) {
    if (check) {
      problems.push(`${path.join('ru', page)} — missing; run \`npm run ru:sync\` and translate it`);
      continue;
    }

    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, placeholderFor(page));
    created += 1;
    continue;
  }

  if (!check) continue;

  const russian = fs.readFileSync(target, 'utf-8');
  const relative = path.join('ru', page);

  if (isPlaceholder(russian)) {
    problems.push(`${relative} — still the English placeholder`);
    continue;
  }

  // The description is the snippet a Russian search result shows; left in English it is the one
  // piece of the page a reader sees before deciding not to click.
  const description = /^description:\s*(.+)$/m.exec(splitFrontmatter(russian)[0] || '');
  if (description && !/[а-яё]/i.test(description[1])) {
    problems.push(`${relative} — the frontmatter description is still English`);
  }

  const share = cyrillicShare(russian);
  if (share < MIN_CYRILLIC_SHARE) {
    problems.push(`${relative} — prose is ${Math.round(share * 100)} % Cyrillic, below the ${Math.round(MIN_CYRILLIC_SHARE * 100)} % a finished translation reaches`);
  }

  const english = headings(fs.readFileSync(path.join(SRC_DIR, page), 'utf-8')).map((heading) => heading.anchor);
  const translated = headings(russian);
  const missing = english.filter((anchor) => !translated.some((heading) => heading.anchor === anchor));

  if (missing.length > 0) {
    problems.push(`${relative} — headings lost the English anchors ${missing.map((anchor) => `#${anchor}`).join(', ')}; add \`{#anchor}\` to the translated heading`);
  }

  const escaping = [...russian.matchAll(/\]\(\/(?!ru\/)([^)\s]*)/g)]
    .map((match) => `/${match[1]}`)
    .filter((link) => !/\.(png|jpe?g|svg|webp|txt|xml|ico)$/.test(link));

  if (escaping.length > 0) {
    problems.push(`${relative} — links leave the locale: ${[...new Set(escaping)].join(', ')}`);
  }
}

const stale = removeStalePages(pages);
if (check) problems.push(...stale.map((page) => `${page} — no English original; delete it`));

if (check) {
  if (problems.length > 0) {
    console.error(`docs-site/ru — ${problems.length} problem${problems.length === 1 ? '' : 's'}:\n`);
    for (const problem of problems) console.error(`  ${problem}`);
    console.error('\nEvery English page needs a Russian translation that keeps the English heading anchors.');
    process.exit(1);
  }

  console.log(`docs-site/ru — ${pages.length} pages translated, anchors and links in step`);
} else {
  console.log(
    `docs-site/ru — ${pages.length} pages${created ? `, ${created} placeholder${created === 1 ? '' : 's'} created` : ''}${stale.length ? `, ${stale.length} stale removed` : ''}`,
  );
}
