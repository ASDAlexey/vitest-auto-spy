#!/usr/bin/env node
// Replaces the generated `dist/node.d.cts` with a thin re-export of its own ESM twin.
//
// Why this exists: the CJS build is a second tsup config object, so `rollup-dts` runs over it
// separately and inlines the entire type surface again. The result is the single largest file in
// the published package — 92 317 B, 1 829 lines, two thirds of it byte-identical to `bun.d.ts` —
// where `dist/node.d.ts` says the same thing in seven re-export lines by sharing the emitted
// chunks. Nothing in CJS needs that duplication: a declaration file describes shapes, and the
// shapes are already declared next door.
//
// The shape below is the one that actually type-checks, and it is not the obvious one. Measured
// against this repo's own tsc, with a `.cts` consumer that uses both a value and a type:
//
//   export * from './node.js'                    → TS1479: a CommonJS file cannot `require` an ESM one
//   export type * from './node.js'               → TS1479 as well, without `resolution-mode`
//   import type * as N + `export = N`            → values fine, every *type* alias lost (TS2305 on `Spy`)
//   export type * … with resolution-mode          → types fine, values become type-only (TS1362)
//
// So the two halves are split: `export type *` carries every type across the boundary in one line,
// and the values — which that line deliberately excludes — are re-declared by name against the same
// namespace. The names come from the built ESM module's own runtime exports, so the list cannot
// drift from what `dist/node.cjs` actually provides.
//
// Verified clean under `module`/`moduleResolution` `node16` *and* `nodenext`, with
// `verbatimModuleSyntax` both off and on.
//
// Usage:
//   node scripts/thin-node-cts.mjs           # rewrite dist/node.d.cts
//   node scripts/thin-node-cts.mjs --check   # exit 1 if it is not already thin (CI)
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const ESM_ENTRY = 'dist/node.js';
const CJS_TYPES = 'dist/node.d.cts';

// A named export has to be reachable as `Entry.<name>`, which a string-literal export name
// (`export { x as 'not an identifier' }`) is not. None exist today; this fails loudly rather than
// emitting a declaration file that does not parse if one ever does.
const IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function fail(message) {
  console.error(`thin-node-cts: ${message}`);
  process.exit(1);
}

const namespace = await import(pathToFileURL(ESM_ENTRY).href);
const values = Object.keys(namespace)
  .filter((name) => name !== 'default')
  .sort();

if (values.length === 0) {
  fail(`${ESM_ENTRY} exported no named values — the build is broken, refusing to write an empty declaration`);
}

const invalid = values.filter((name) => !IDENTIFIER_RE.test(name));

if (invalid.length > 0) {
  fail(`export names are not identifiers and cannot be re-declared: ${invalid.join(', ')}`);
}

const contents = [
  '// Generated by scripts/thin-node-cts.mjs — do not edit.',
  '//',
  '// `dist/node.d.ts` is the real declaration; this file re-states it for CommonJS consumers. Types',
  "// cross the boundary in one `export type *`; values cannot ride along with it (they would come",
  '// through as type-only), so they are re-declared by name against the same namespace.',
  '',
  "export type * from './node.js' with { 'resolution-mode': 'import' };",
  '',
  "import type * as Entry from './node.js' with { 'resolution-mode': 'import' };",
  '',
  ...values.map((name) => `export declare const ${name}: typeof Entry.${name};`),
  '',
].join('\n');

const before = statSync(CJS_TYPES).size;

if (process.argv.includes('--check')) {
  if (readFileSync(CJS_TYPES, 'utf8') !== contents) {
    fail(`${CJS_TYPES} is stale (${before} B) — run \`npm run build\``);
  }

  console.log(`thin-node-cts: up to date (${before} B, ${values.length} value exports)`);
  process.exit(0);
}

writeFileSync(CJS_TYPES, contents);

console.log(`thin-node-cts: ${CJS_TYPES} ${before} B → ${contents.length} B (${values.length} value exports)`);
