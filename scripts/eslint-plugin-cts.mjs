#!/usr/bin/env node
// Rewrites `dist/eslint-plugin.d.cts` so the `require` condition's types describe what `require`
// actually returns.
//
// `dist/eslint-plugin.cjs` ends in `module.exports = plugin`, so
// `require('vitest-auto-spy/eslint-plugin')` hands back the plugin object itself. The declaration
// rollup emits the same file for both conditions, and in CommonJS its `export { plugin as default }`
// means `exports.default` — the classic masquerading default. The effect is that TypeScript rejects
// the code that works:
//
//   import plugin = require('vitest-auto-spy/eslint-plugin');
//   plugin.rules;         // runs; TS2339 before this file existed
//   plugin.default.rules; // type-checks; TypeError at runtime
//
// which reaches every `eslint.config.cts` and every `eslint.config.cjs` checked with `checkJs`.
//
// The shape below is the `export =` form those consumers need, with the named types re-stated
// inside the merged namespace so `plugin.FlatConfig` keeps resolving. Types cross the boundary
// through the ESM declaration, the same way `thin-node-cts.mjs` does it for `./node`, so there is
// one declaration of each type and nothing to drift.
//
// Usage:
//   node scripts/eslint-plugin-cts.mjs           # rewrite dist/eslint-plugin.d.cts
//   node scripts/eslint-plugin-cts.mjs --check   # exit 1 if it is not already the export = form
import { readFileSync, statSync, writeFileSync } from 'node:fs';

const ESM_TYPES = 'dist/eslint-plugin.d.ts';
const CJS_TYPES = 'dist/eslint-plugin.d.cts';
const RUNTIME = 'dist/eslint-plugin.cjs';

function fail(message) {
  console.error(`eslint-plugin-cts: ${message}`);
  process.exit(1);
}

/** The type names the ESM declaration exports, read off its final `export { … }` statement. */
function exportedTypes(source) {
  const statement = source.match(/export \{([^}]*)\};/g)?.at(-1);

  if (statement === undefined) {
    fail(`${ESM_TYPES} has no export statement — has the declaration build changed shape?`);
  }

  const names = [...statement.matchAll(/type (\w+)/g)].map(([, name]) => name);

  if (names.length === 0) {
    fail(`${ESM_TYPES} exports no types — refusing to write a declaration that loses them`);
  }

  return names;
}

const esm = readFileSync(ESM_TYPES, 'utf8');
const runtime = readFileSync(RUNTIME, 'utf8');

if (!/module\.exports = \w+;\s*$/.test(runtime)) {
  fail(`${RUNTIME} no longer ends in \`module.exports = …\` — this file would then describe the wrong shape`);
}

if (!/\bplugin as default\b/.test(esm)) {
  fail(`${ESM_TYPES} no longer exports \`plugin\` as its default — check what the CJS build assigns`);
}

const types = exportedTypes(esm);
const pluginType = types.includes('AutoSpyEslintPlugin') ? 'AutoSpyEslintPlugin' : types[0];

const contents = [
  '// Generated by scripts/eslint-plugin-cts.mjs — do not edit.',
  '//',
  '// `dist/eslint-plugin.cjs` ends in `module.exports = plugin`, so `require()` of this entry',
  '// returns the plugin object itself rather than a module namespace with a `default` on it. The',
  '// types have to say the same thing, which in CommonJS is `export =`.',
  '',
  "import type * as Plugin from './eslint-plugin.js' with { 'resolution-mode': 'import' };",
  '',
  `declare const plugin: Plugin.${pluginType};`,
  '',
  'declare namespace plugin {',
  ...types.map((name) => `  export type ${name} = Plugin.${name};`),
  '}',
  '',
  'export = plugin;',
  '',
].join('\n');

const before = statSync(CJS_TYPES).size;

if (process.argv.includes('--check')) {
  if (readFileSync(CJS_TYPES, 'utf8') !== contents) {
    fail(`${CJS_TYPES} is stale (${before} B) — run \`npm run build\``);
  }

  console.log(`eslint-plugin-cts: up to date (${before} B, ${types.length} types)`);
  process.exit(0);
}

writeFileSync(CJS_TYPES, contents);

console.log(`eslint-plugin-cts: ${CJS_TYPES} ${before} B → ${contents.length} B (export =, ${types.length} types)`);
