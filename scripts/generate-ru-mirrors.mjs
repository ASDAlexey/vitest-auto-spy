#!/usr/bin/env node

/**
 * Mirrors every English documentation page under `docs-site/ru/`, so the Russian locale has a page
 * at the same path. Only the landing is translated; a mirror carries the English body under the
 * Russian chrome, which is what keeps the language switcher on the current page instead of dropping
 * the reader on `/ru/`, and what gives the local search a Russian-locale index to search at all.
 *
 * The mirrors are generated, never committed: `docs-site/ru/*` is git-ignored apart from
 * `index.md`, and `predev` / `prebuild` regenerate them.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = path.join(ROOT, 'docs-site');
const RU_DIR = path.join(SRC_DIR, 'ru');

const SKIP_DIRS = new Set(['node_modules', '.vitepress', 'public', 'ru']);
const SKIP_FILES = new Set(['README.md']);

const BANNER = '<!-- Generated by scripts/generate-ru-mirrors.mjs — edit the English page instead. -->';

function collectPages(dir, prefix = '') {
  const pages = [];

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      pages.push(...collectPages(path.join(dir, entry.name), `${prefix}${entry.name}/`));
      continue;
    }

    if (!entry.name.endsWith('.md') || SKIP_FILES.has(entry.name)) continue;
    if (prefix === '' && entry.name === 'index.md') continue;

    pages.push(`${prefix}${entry.name}`);
  }

  return pages;
}

// Absolute in-site links have to gain the `/ru` prefix or a click leaves the locale; relative ones
// already resolve inside the mirror, and anything with a scheme is somebody else's site.
function localizeLinks(markdown) {
  return markdown.replace(/\]\(\/(?!\/)/g, '](/ru/');
}

function splitFrontmatter(markdown) {
  const match = /^---\r?\n[\s\S]*?\r?\n---\r?\n/.exec(markdown);
  return match ? [match[0], markdown.slice(match[0].length)] : ['', markdown];
}

function mirror(page) {
  const source = fs.readFileSync(path.join(SRC_DIR, page), 'utf-8');
  const [frontmatter, body] = splitFrontmatter(source);
  const target = path.join(RU_DIR, page);

  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, `${frontmatter}\n${BANNER}\n${localizeLinks(body)}`);
}

function removeStaleMirrors(pages) {
  const keep = new Set(pages.map((page) => path.join(RU_DIR, page)));
  let removed = 0;

  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);

      if (entry.isDirectory()) {
        walk(full);
        if (fs.readdirSync(full).length === 0) fs.rmdirSync(full);
        continue;
      }

      if (full === path.join(RU_DIR, 'index.md') || keep.has(full)) continue;
      fs.unlinkSync(full);
      removed += 1;
    }
  };

  if (fs.existsSync(RU_DIR)) walk(RU_DIR);
  return removed;
}

const pages = collectPages(SRC_DIR);
pages.forEach(mirror);
const removed = removeStaleMirrors(pages);

console.log(`docs-site/ru — ${pages.length} mirrored pages${removed ? `, ${removed} stale removed` : ''}`);
